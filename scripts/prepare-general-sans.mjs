// Gets the General Sans font files before dev/build, without them ever being committed.
// The ITF Free Font License allows self hosting on this site but not sharing the files in a public repo,
// so the original, unmodified files live in a private Vercel Blob store and are downloaded here.
// Then it writes .generated/general-sans.ts, which loads them with next/font/local,
// or falls back to Arial when the files aren't available (for example in a fresh clone).
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedDir = path.join(root, ".generated");
const fontDir = path.join(root, "public", "fonts", "general-sans");
const generatedModule = path.join(generatedDir, "general-sans.ts");
const manifest = JSON.parse(await readFile(path.join(root, "scripts", "general-sans-assets.json"), "utf8"));
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

// Vercel supplies this variable during builds. Locally it can come from the git-ignored .env.local.
if (!process.env.BLOB_READ_WRITE_TOKEN && existsSync(path.join(root, ".env.local"))) {
  const env = await readFile(path.join(root, ".env.local"), "utf8");
  const match = env.match(/^BLOB_READ_WRITE_TOKEN=(.*)$/m);
  if (match) {
    const value = match[1].trim();
    try {
      process.env.BLOB_READ_WRITE_TOKEN = value.startsWith('"') ? JSON.parse(value) : value.replace(/^'|'$/g, "");
    } catch {
      throw new Error("General Sans: unable to read the Blob token from the ignored local env file.");
    }
  }
}

if (manifest.fonts.length !== 4 || [400, 500, 600, 700].some((weight) => !manifest.fonts.some((font) => font.weight === weight)) || !manifest.license) {
  throw new Error("General Sans: configure the four original font files and license in the asset manifest.");
}

// True when every font file (and the license) is already present and unmodified.
async function haveVerifiedFiles() {
  for (const asset of [...manifest.fonts, manifest.license]) {
    const file = path.join(fontDir, asset.filename);
    if (!existsSync(file) || sha256(await readFile(file)) !== asset.sha256) return false;
  }
  return true;
}

const token = process.env.BLOB_READ_WRITE_TOKEN;
if (token) {
  await mkdir(fontDir, { recursive: true });
  for (const asset of [...manifest.fonts, manifest.license]) {
    const source = new URL(asset.url);
    if (source.protocol !== "https:" || !source.hostname.endsWith(".private.blob.vercel-storage.com") || path.basename(asset.filename) !== asset.filename) {
      throw new Error("General Sans: invalid private Blob asset configuration.");
    }
    const response = await fetch(source, {
      headers: { Authorization: `Bearer ${token}` },
      signal: AbortSignal.timeout(30000),
    });
    if (!response.ok) throw new Error(`General Sans: asset download failed (HTTP ${response.status}).`);
    const bytes = Buffer.from(await response.arrayBuffer());
    if (asset.weight && bytes.subarray(0, 4).toString("ascii") !== "wOF2") throw new Error("General Sans: expected an unmodified WOFF2 font.");
    if (sha256(bytes) !== asset.sha256) throw new Error("General Sans: downloaded asset does not match the original file.");
    await writeFile(path.join(fontDir, asset.filename), bytes);
  }
}

const available = await haveVerifiedFiles();
await mkdir(generatedDir, { recursive: true });

if (available) {
  const src = manifest.fonts
    .map((font) => `    { path: "../public/fonts/general-sans/${font.filename}", weight: "${font.weight}", style: "normal" },`)
    .join("\n");
  await writeFile(
    generatedModule,
    `// Generated by scripts/prepare-general-sans.mjs. Do not edit, do not commit.
import localFont from "next/font/local";

export const generalSans = localFont({
  src: [
${src}
  ],
  display: "swap",
  variable: "--nf-general-sans",
  fallback: ["Arial", "sans-serif"],
  adjustFontFallback: "Arial",
  // next/font can only preload all four files or none. The mobile hero only needs 600, so none are preloaded; they load during the first render with a size matched fallback.
  preload: false,
});
`
  );
  console.log(token ? "General Sans: verified the original files from the private Blob store." : "General Sans: using the verified local files.");
} else {
  // No fonts: --nf-general-sans keeps its Arial default from globals.css.
  await writeFile(
    generatedModule,
    `// Generated by scripts/prepare-general-sans.mjs. Do not edit, do not commit.
// General Sans isn't available in this build, so headings use the Arial fallback.
export const generalSans = { variable: "" };
`
  );
  console.log("General Sans: font files not available (no Blob token); headings use the Arial fallback.");
}
